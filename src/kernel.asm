section .text
BITS 32
CODE_SEG equ 0x08
DATA_SEG equ 0x10
TSS_SEG equ 0x18

; ALLOCATION LIST
;
; 0x0500-0x05FF: AHCI RECEIVED FIS
; 0x0600-0x07FF: AHCI BUFFER
; 0x0800-0x0BFF: AHCI COMMAND LIST
; 0x0C00-0x0CFF: AHCI COMMAND TABLE
; 0x5000-0x5068: TSS
; 0x7C00-0xFFFF: KERNEL
;
; -=-=-=-=-=-=-=-=-=-=-=-

global _start
_start:

MOV AX,DATA_SEG
MOV DS,AX
MOV ES,AX
MOV FS,AX
MOV GS,AX
MOV SS,AX

MOV ESP,stack_high
MOV EDI,0x500C
MOV DWORD [EDI-12],0
MOV [EDI-8],ESP
MOV [EDI-4],AX

CLD
XOR EAX,EAX
MOV ECX,23
REP STOSD ; zero out the rest of the TSS

MOV DI,0x500
MOV CH,0x2 ; ECX=0x00000200
REP STOSD ; zero out the AHCI command list and received FIS

MOV AX,TSS_SEG
LTR AX

JMP _main

