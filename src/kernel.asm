; CLOBBERS: EAX, ECX, EDX
; ================ scroll ================
global scroll
scroll:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI
	PUSH EDI

	MOV ESI,[EBP+8]
	CMP ESI,25
	JA scroll_clear

	MOV EAX,160
	MUL ESI
	MOV EDX,EAX

	MOV EDI,0xB8000
	LEA ESI,[EDX+EDI]

	MOV ECX,4000
	SUB ECX,EDX
	SHR ECX,2
	CLD
	REP MOVSD

	MOV ECX,EDX
	SHR ECX,1
	MOV AH,[G_Printing_TextAttribute]
	XOR AL,AL
	REP STOSW

	SHR EDX,1
	MOV AX,[G_Printing_TextCursor]
	SUB AX,DX
	JC scroll_curse
	MOV [G_Printing_TextCursor],AX
	CALL blink
	JMP scroll_end

	scroll_curse:
	MOV WORD [G_Printing_TextCursor],0

	scroll_end:
	POP EDI
	POP ESI
	POP EBP
	RET

	scroll_clear:
	CALL clear
	JMP scroll_end


