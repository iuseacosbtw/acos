; ================ cmpstr ================
; Compares two strings
; Returns 1 if they are equal
; Returns 0 if they are not
;
; ARGS: char* str1,char* str2
; OUTPUT: byte
; CLOBBERS: EAX
; ================ cmpstr ================
global cmpstr
cmpstr:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI
	PUSH EDI

	MOV ESI,[EBP+8]
	MOV EDI,[EBP+12]
	XOR EAX,EAX
	CLD

	cmpstr_loop:
		CMPSB
		JNE cmpstr_failure
		CMP BYTE [ESI],0
		JE cmpstr_loop_end
		CMP BYTE [EDI],0
		JE cmpstr_failure

		JMP cmpstr_loop
		cmpstr_loop_end:
			CMP BYTE [EDI],0
			JNE cmpstr_failure

	cmpstr_success:
	INC EAX
	cmpstr_failure:

	POP EDI
	POP ESI
	POP EBP
	RET

