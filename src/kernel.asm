read_pci:
	PUSH EBP
	MOV EBP,ESP
	PUSH EBX

	MOV EAX,0x80000000

	MOV EBX,[EBP+8] ; bus
	SHL EBX,16
	OR EAX,EBX

	MOV EBX,[EBP+12] ; device
	AND EBX,0x1F
	SHL EBX,11
	OR EAX,EBX

	MOV EBX,[EBP+16] ; function
	AND EBX,0x07
	SHL EBX,8
	OR EAX,EBX

	MOV EBX,[EBP+20] ; offset
	AND EBX,0xFC
	OR EAX,EBX

	MOV DX,0xCF8
	OUT DX,EAX
	MOV DX,0xCFC
	IN EAX,DX

	POP EBX
	POP EBP
	RET


