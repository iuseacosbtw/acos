; ================================ -PRINTING- ================================
; This section is for printing text on the screen.
; It involves manipulating the cursor and printing strings.
; Not much else to it.

global G_Printing_TextCursor
G_Printing_TextCursor: dw 0 ; location of the text cursor
global G_Printing_TextAttribute
G_Printing_TextAttribute: db 0x0F ; attribute of the next character to be typed

; ================ setcursorpos ================
; Sets the position of the text cursor.
; x must be between 0 and 79.
; y must be between 0 and 24.
; If x and y are not between these limits, they will be assumed to be 0.
;
; ARGS: x, y
; OUTPUT: void
; CLOBBERS: EAX, ECX, EDX
; ================ setcursorpos ================
global setcursorpos
setcursorpos:
	PUSH EBP
	MOV EBP,ESP

	XOR CH,CH
	MOV AX,[EBP+12]
	CMP AX,25
	JB setcursorpos_yisvalid
	INC CH
	SUB AX,24
	setcursorpos_yisvalid:
	MOV DX,[EBP+8]
	CMP DX,80
	JB setcursorpos_xisvalid
	XOR DX,DX
	setcursorpos_xisvalid:

	OR CH,CH
	JNZ setcursorpos_scroll
	setcursorpos_ret:

	MOV CL,80
	MUL CL
	ADD AX,DX
	MOV [G_Printing_TextCursor],AX

	POP EBP
	RET

	setcursorpos_scroll:
	PUSH ECX
	PUSH EDX
	PUSH EAX
	CALL scroll
	POP EAX
	POP EDX
	POP ECX
	MOV EAX,24
	JMP setcursorpos_ret

; ================ getcursorpos ================
; Gets the current position of the text cursor.
;
; ARGS: void
; OUTPUT: AL=x, DL=y
; CLOBBERS: EAX, CX, EDX
; ================ getcursorpos ================
; NO GLOBAL!!!
getcursorpos:
	XOR EDX,EDX
	MOV EAX,[G_Printing_TextCursor]
	MOV CX,80
	DIV CX
	XCHG EAX,EDX

	RET

; ================ blink ================
; Updates the visible location of the cursor.
; Meant to be used internally, by other functions,
; or if you modify G_Printing_TextCursor specifically.
;
; ARGS: void
; OUTPUT: void
; CLOBBERS: AX, DX
; ================ blink ================
; NO GLOBAL!!!
blink:
	PUSH EBX

	MOV DX,0x3D4
	MOV AL,0x0F
	OUT DX,AL

	INC DX
	MOV AX,[G_Printing_TextCursor]
	OUT DX,AL

	MOVZX EBX,AX
	ADD EBX,0xB8000/2
	MOV AL,DL
	MOV DL,[G_Printing_TextAttribute]
	MOV [EBX*2+1],DL
	MOV DL,AL

	DEC DX
	MOV AL,0x0E
	OUT DX,AL

	INC DX
	MOV AL,AH
	OUT DX,AL

	POP EBX
	RET

; ================ printc ================
; Prints the character onto the screen, handling newlines, backspaces, etc.
;
; ARGS: char
; OUTPUT: void
; CLOBBERS: EAX, CX, EDX
; ================ printc ================
global printc
printc:
	PUSH EBP
	MOV EBP,ESP
	PUSH EBX

	MOVZX EBX,WORD [G_Printing_TextCursor]
	ADD EBX,0xB8000/2 ; we're gonna shift right
	ADD EBX,EBX ; EBX now contains offset

	MOV EAX,[EBP+8]

	CMP AL,0x20
	JAE printc_not_ctrl_char
	CMP AL,0x0A ; line feed
	JE printc_lf
	CMP AL,0x0D ; carriage return
	JE printc_cr
	CMP AL,0x08 ; backspace
	JE printc_bksp

	CMP AL,0x01 ; up
	JE printc_up
	CMP AL,0x02 ; left
	JE printc_left
	CMP AL,0x03 ; down
	JE printc_down
	CMP AL,0x04 ; right
	JE printc_right
	JMP printc_null
	printc_not_ctrl_char:

	MOV [EBX],AL
	MOV AL,[G_Printing_TextAttribute]
	MOV [EBX+1],AL

	printc_right:
	INC WORD [G_Printing_TextCursor]
	CMP WORD [G_Printing_TextCursor],2000
	JB printc_cleanup

	PUSH DWORD 25
	PUSH DWORD 0
	CALL setcursorpos
	ADD ESP,8

	printc_cleanup:
	CALL blink
	printc_null:
	POP EBX
	POP EBP
	RET

	printc_lf:
		CALL getcursorpos

		CMP DX,24
		INC DX
		JB printc_lf_continue
		PUSH EDX
		PUSH DWORD 1
		CALL scroll
		ADD ESP,4
		POP EDX
		DEC DX

		printc_lf_continue:
		PUSH EDX
		PUSH DWORD 0
		CALL setcursorpos
		ADD ESP,8
		JMP printc_cleanup
	printc_cr:
		CALL getcursorpos
		PUSH EDX
		PUSH DWORD 0
		CALL setcursorpos
		ADD ESP,8
		JMP printc_cleanup
	printc_bksp:
		CMP WORD [G_Printing_TextCursor],0
		JE printc_cleanup
		DEC WORD [G_Printing_TextCursor]
		DEC EBX
		MOV AL,[G_Printing_TextAttribute]
		MOV [EBX],AL
		DEC EBX
		MOV BYTE [EBX],0x20
		JMP printc_cleanup

	printc_up:
		CALL getcursorpos
		CMP DL,0
		JE printc_cleanup
		DEC EDX
		PUSH EDX
		PUSH EAX
		CALL setcursorpos
		ADD ESP,8
		JMP printc_cleanup
	printc_left:
		CALL getcursorpos
		CMP AL,0
		JE printc_cleanup
		DEC WORD [G_Printing_TextCursor]
		JMP printc_cleanup
	printc_down:
		CALL getcursorpos
		INC EDX
		PUSH EDX
		PUSH EAX
		CALL setcursorpos
		ADD ESP,8
		JMP printc_cleanup

; ================ prints ================
; Prints the string onto the screen, using printc for each character.
; Stops printing once it reaches a 0x00 byte.
;
; ARGS: char*
; OUTPUT: void
; CLOBBERS: EAX, CX, EDX
; ================ prints ================
global prints
prints:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI

	MOV ESI,[EBP+8]
	CLD

	prints_loop:
		CMP BYTE [ESI],0
		JE prints_cleanup
		PUSH DWORD [ESI]
		CALL printc
		ADD ESP,4
		INC ESI
		JMP prints_loop

	prints_cleanup:
	CALL blink
	POP ESI
	POP EBP
	RET
global prints_prog

prints_prog:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI

	MOV ESI,[EBP+8]
	CLD

	prints_prog_loop:
		CMP BYTE [GS:ESI],0
		JE prints_prog_cleanup
		PUSH DWORD [GS:ESI]
		CALL printc
		ADD ESP,4
		INC ESI
		JMP prints_prog_loop

	prints_prog_cleanup:
	CALL blink
	POP ESI
	POP EBP
	RET

; ================ prints_raw ================
; Prints the string onto the screen, printing each character exactlty as-is.
; Stops printing once it reaches a 0x00 byte.
;
; ARGS: char*
; OUTPUT: void
; CLOBBERS: AX, DX
; ================ prints_raw ================
global prints_raw
prints_raw:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI
	PUSH EDI

	MOV ESI,[EBP+8]
	MOV DX,[G_Printing_TextCursor]

	MOVZX EDI,DX ; same routine as printc
	ADD EDI,0xB8000/2
	ADD EDI,EDI

	MOV AL,[G_Printing_TextAttribute]
	CLD

	prints_raw_loop:
		CMP BYTE [ESI],0
		JE prints_raw_cleanup
		MOVSB
		MOV [EDI],AL
		INC EDI
		INC DX
		JMP prints_raw_loop

	prints_raw_cleanup:
	MOV [G_Printing_TextCursor],DX
	CALL blink
	POP EDI
	POP ESI
	POP EBP
	RET
global prints_raw_prog

prints_raw_prog:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI
	PUSH EDI

	MOV ESI,[EBP+8]
	MOV DX,[G_Printing_TextCursor]

	MOVZX EDI,DX ; same routine as printc
	ADD EDI,0xB8000/2
	ADD EDI,EDI

	MOV AL,[G_Printing_TextAttribute]
	CLD

	prints_raw_prog_loop:
		CMP BYTE [GS:ESI],0
		JE prints_raw_prog_cleanup
		GS MOVSB
		MOV [EDI],AL
		INC EDI
		INC DX
		JMP prints_raw_prog_loop

	prints_raw_prog_cleanup:
	MOV [G_Printing_TextCursor],DX
	CALL blink
	POP EDI
	POP ESI
	POP EBP
	RET

; ================ printc_raw ================
; Prints the character onto the screen, as-is.
;
; ARGS: char
; OUTPUT: void
; CLOBBERS: AX, DX
; ================ printc_raw ================
global printc_raw
printc_raw:
	PUSH EBP
	MOV EBP,ESP
	PUSH EBX

	MOVZX EBX,WORD [G_Printing_TextCursor]
	ADD EBX,0xB8000/2
	ADD EBX,EBX

	MOV EAX,[EBP+8]
	MOV [EBX],AL
	MOV AL,[G_Printing_TextAttribute]
	MOV [EBX+1],AL

	INC WORD [G_Printing_TextCursor]
	CALL blink

	POP EBX
	POP EBP
	RET

; ================ printh ================
; Prints a byte, two hex digits, onto the screen.
;
; ARGS: char
; OUTPUT: void
; CLOBBERS: AX, DX
; ================ printh ================
global printh
printh:
	PUSH EBP
	MOV EBP,ESP

	;MOV DX,[G_Printing_TextCursor]
	;MOVZX EBX,DX
	;ADD EBX,0xB8000/2
	;ADD EBX,EBX

	MOV AL,[EBP+8] ; first digit
	SHR AL,4
	ADD AL,'0'
	CMP AL,'9'
	JBE printh_1good

	ADD AL,'A'-0x3A

	printh_1good:
	PUSH EAX
	CALL printc
	POP EAX

	MOV AL,[EBP+8]
	AND AL,0x0F
	ADD AL,'0'
	CMP AL,'9'
	JBE printh_2good

	ADD AL,'A'-0x3A

	printh_2good:
	PUSH EAX
	CALL printc
	POP EAX

	CALL blink
	POP EBP
	RET

; ================ clear ================
; Clears the screen and resets the cursor.
;
; ARGS: void
; OUTPUT: void
; CLOBBERS: EAX, ECX, DX
; ================ clear ================
global clear
clear:
	PUSH EDI

	XOR EAX,EAX
	MOV [G_Printing_TextCursor],AX
	MOV EDI,0xB8000
	MOV ECX,1000
	REP STOSD

	CALL blink
	POP EDI
	RET

; ================ panic ================
; Clears the screen prints the kernel panic message.
;
; ARGS: char*
; OUTPUT: void
; CLOBBERS: EAX, ECX, DX
; ================ panic ================
global panic
panic:
	PUSH EBP
	MOV EBP,ESP

	CALL clear
	MOV BYTE [G_Printing_TextAttribute],0x8C
	PUSH panic_str
	CALL prints
	ADD ESP,4
	MOV BYTE [G_Printing_TextAttribute],0x0F

	PUSH DWORD [EBP+8]
	CALL prints
	ADD ESP,4

	POP EBP
	RET

global panic_prog
panic_prog:
	PUSH EBP
	MOV EBP,ESP

	CALL clear
	MOV BYTE [G_Printing_TextAttribute],0x8C
	PUSH panic_str
	CALL prints
	ADD ESP,4
	MOV BYTE [G_Printing_TextAttribute],0x0F

	PUSH DWORD [EBP+8]
	CALL prints_prog
	ADD ESP,4

	POP EBP
	RET
panic_str: db "KERNEL PANIC",0x0A,0

